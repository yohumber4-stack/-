function resolve(table, ch) {
  let g = table[ch];
  if (typeof g === 'string') g = table[g];
  return g;
}

export const FONT = { big: { table: G7, h: 7, space: 3 }, small: { table: G5, h: 5, space: 2 } };

export function textWidth(str, font = 'big', spacing = 1) {
  const f = FONT[font];
  let w = 0;
  for (const raw of str) {
    const ch = raw.toUpperCase() === raw ? raw : font === 'small' && raw === 'o' ? raw : raw.toUpperCase();
    const g = resolve(f.table, ch);
    w += (g ? g[0].length : f.space) + spacing;
  }
  return Math.max(0, w - spacing);
}

// Draw text. opts: font ('big'|'small'), scale, align ('left'|'center'|'right'), spacing, shadow colour, outline colour
export function text(fb, str, x, y, color, o = {}) {
  const font = o.font || 'big', f = FONT[font], sc = o.scale || 1, sp = o.spacing === undefined ? 1 : o.spacing;
  const w = textWidth(str, font, sp) * sc;
  let cx = o.align === 'center' ? Math.round(x - w / 2) : o.align === 'right' ? x - w : x;
  if (o.outline !== undefined || o.shadow !== undefined) {
    // draw to scratch and outline for crisp result
    const tmp = new FB(w + 2, f.h * sc + 2).clear();
    text(tmp, str, 1, 1, color, { ...o, align: 'left', outline: undefined, shadow: undefined });
    if (o.shadow !== undefined) {
      const d = o.shadowD || 1;
      fb.blit(o.outline !== undefined ? outlined(tmp, o.shadow) : tmp, cx - 1 + d, y - 1 + d, { solid: o.shadow });
    }
    fb.blit(o.outline !== undefined ? outlined(tmp, o.outline) : tmp, cx - (o.outline !== undefined ? 2 : 1), y - (o.outline !== undefined ? 2 : 1));
    return w;
  }
  let n = 0;
  const limit = o.chars === undefined ? Infinity : o.chars;
  for (const raw of str) {
    if (n++ >= limit) break;
    const ch = font === 'small' && raw === 'o' ? raw : raw.toUpperCase();
    const g = resolve(f.table, ch);
    if (!g) { cx += (f.space + sp) * sc; continue; }
    const gw = g[0].length;
    const col = typeof color === 'function' ? color(n - 1) : color;
    for (let gy = 0; gy < g.length; gy++)
      for (let gx = 0; gx < gw; gx++)
        if (g[gy][gx] === '#') {
          if (sc === 1) fb.set(cx + gx, y + gy, col);
          else fb.rect(cx + gx * sc, y + gy * sc, sc, sc, col);
        }
    cx += (gw + sp) * sc;
  }
  return w;
}
